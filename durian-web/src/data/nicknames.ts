// 上次抽到的下标，避免连续两次抽出同一个昵称
let lastIndex = -1;

export function randomNickname(): string {
  if (NICKNAMES.length === 0) return "玩家";
  if (NICKNAMES.length === 1) return NICKNAMES[0];
  let index = lastIndex;
  while (index === lastIndex) index = Math.floor(Math.random() * NICKNAMES.length);
  lastIndex = index;
  return NICKNAMES[index];
}
